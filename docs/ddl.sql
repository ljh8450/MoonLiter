ALTER TABLE app_users
    ADD COLUMN IF NOT EXISTS email_verified_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS verified_phone_e164 VARCHAR(32),
    ADD COLUMN IF NOT EXISTS verified_phone_hash VARCHAR(128),
    ADD COLUMN IF NOT EXISTS phone_verified_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS suspension_count INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS suspended_until TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS permanently_suspended BOOLEAN NOT NULL DEFAULT FALSE;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
          FROM pg_constraint
         WHERE conname = 'uk_app_users_verified_phone_hash'
    ) THEN
        ALTER TABLE app_users
            ADD CONSTRAINT uk_app_users_verified_phone_hash UNIQUE (verified_phone_hash);
    END IF;
END;
$$;

ALTER TABLE app_users
    DROP CONSTRAINT IF EXISTS app_users_status_check;

ALTER TABLE app_users
    ADD CONSTRAINT app_users_status_check
    CHECK (status IN ('ACTIVE', 'SUSPENDED', 'BLOCKED', 'WITHDRAWN'));

CREATE TABLE IF NOT EXISTS user_suspensions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    admin_id BIGINT NOT NULL REFERENCES app_users(id),
    reason VARCHAR(500) NOT NULL,
    suspension_count INTEGER NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ,
    permanent BOOLEAN NOT NULL,
    released_at TIMESTAMPTZ,
    release_reason VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_user_suspensions_user_created_at
    ON user_suspensions(user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_user_suspensions_active_user
    ON user_suspensions(user_id)
    WHERE released_at IS NULL;

CREATE TABLE IF NOT EXISTS app_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    type VARCHAR(50) NOT NULL,
    title VARCHAR(120) NOT NULL,
    body VARCHAR(1000) NOT NULL,
    read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_app_notifications_user_created_at
    ON app_notifications(user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS phone_verification_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    phone_e164 VARCHAR(32) NOT NULL,
    phone_hash VARCHAR(128) NOT NULL,
    code_hash VARCHAR(120) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    attempts INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_phone_verification_codes_user_phone_created_at
    ON phone_verification_codes(user_id, phone_hash, created_at DESC)
    WHERE consumed_at IS NULL;
