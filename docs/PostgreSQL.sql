-- MoonLiter의 PostgreSQL/Supabase 기준 목표 스키마를 기록한다.
-- 현재 백엔드는 JPA ddl-auto=update를 사용하므로, 이 파일은 수동 적용용이 아니라
-- 목표 스키마와 마이그레이션 기준을 문서화하는 용도다.

CREATE TABLE IF NOT EXISTS app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email VARCHAR(100) NOT NULL,
    auth_provider VARCHAR(30) NOT NULL,
    provider_user_id VARCHAR(120) NOT NULL,
    role VARCHAR(30) NOT NULL DEFAULT 'USER',
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_app_users PRIMARY KEY (id),
    CONSTRAINT uk_app_users_provider_user UNIQUE (auth_provider, provider_user_id),
    CONSTRAINT ck_app_users_auth_provider CHECK (auth_provider IN ('EMAIL', 'GOOGLE', 'KAKAO')),
    CONSTRAINT ck_app_users_role CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_app_users_status CHECK (status IN ('ACTIVE', 'BLOCKED', 'WITHDRAWN'))
);

CREATE INDEX IF NOT EXISTS idx_app_users_email
    ON app_users (email);

CREATE INDEX IF NOT EXISTS idx_app_users_status
    ON app_users (status);

CREATE TABLE IF NOT EXISTS media_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    owner_user_id BIGINT NOT NULL,
    storage_key VARCHAR(512) NOT NULL,
    original_filename VARCHAR(255),
    content_type VARCHAR(100) NOT NULL,
    byte_size BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    uploaded_at TIMESTAMPTZ(6),
    updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_media_files PRIMARY KEY (id),
    CONSTRAINT uk_media_files_storage_key UNIQUE (storage_key),
    CONSTRAINT fk_media_files_owner
        FOREIGN KEY (owner_user_id) REFERENCES app_users (id),
    CONSTRAINT ck_media_files_byte_size_positive
        CHECK (byte_size > 0),
    CONSTRAINT ck_media_files_status
        CHECK (status IN ('PENDING', 'UPLOADED', 'FAILED')),
    CONSTRAINT ck_media_files_content_type
        CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp'))
);

CREATE INDEX IF NOT EXISTS idx_media_files_owner_status
    ON media_files (owner_user_id, status);

CREATE INDEX IF NOT EXISTS idx_media_files_status_created
    ON media_files (status, created_at);

CREATE TABLE IF NOT EXISTS postcards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    author_id BIGINT NOT NULL,
    media_file_id BIGINT,
    content VARCHAR(500) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'DELIVERABLE',
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_postcards PRIMARY KEY (id),
    CONSTRAINT uk_postcards_media_file UNIQUE (media_file_id),
    CONSTRAINT fk_postcards_author
        FOREIGN KEY (author_id) REFERENCES app_users (id),
    CONSTRAINT fk_postcards_media_file
        FOREIGN KEY (media_file_id) REFERENCES media_files (id),
    CONSTRAINT ck_postcards_status
        CHECK (status IN ('DELIVERABLE', 'HIDDEN'))
);

CREATE INDEX IF NOT EXISTS idx_postcards_author_created
    ON postcards (author_id, created_at);

CREATE INDEX IF NOT EXISTS idx_postcards_status_created
    ON postcards (status, created_at);

CREATE TABLE IF NOT EXISTS postcard_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    postcard_id BIGINT NOT NULL,
    receiver_id BIGINT NOT NULL,
    delivered_date DATE NOT NULL,
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_postcard_deliveries PRIMARY KEY (id),
    CONSTRAINT uk_postcard_deliveries_receiver_date UNIQUE (receiver_id, delivered_date),
    CONSTRAINT fk_postcard_deliveries_postcard
        FOREIGN KEY (postcard_id) REFERENCES postcards (id),
    CONSTRAINT fk_postcard_deliveries_receiver
        FOREIGN KEY (receiver_id) REFERENCES app_users (id)
);

CREATE INDEX IF NOT EXISTS idx_postcard_deliveries_postcard
    ON postcard_deliveries (postcard_id);

CREATE INDEX IF NOT EXISTS idx_postcard_deliveries_receiver_created
    ON postcard_deliveries (receiver_id, created_at);

-- 마이그레이션 참고
-- 기존 Supabase 데이터베이스에 app_users, postcards, postcard_deliveries가 이미 있고
-- 사진 업로드 스키마만 추가해야 하는 경우 아래 순서로 적용한다.
-- 컬럼, 인덱스, 제약이 이미 있으면 중복 적용하지 않는다.

CREATE TABLE IF NOT EXISTS media_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    owner_user_id BIGINT NOT NULL,
    storage_key VARCHAR(512) NOT NULL,
    original_filename VARCHAR(255),
    content_type VARCHAR(100) NOT NULL,
    byte_size BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    uploaded_at TIMESTAMPTZ(6),
    updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_media_files PRIMARY KEY (id),
    CONSTRAINT uk_media_files_storage_key UNIQUE (storage_key),
    CONSTRAINT fk_media_files_owner
        FOREIGN KEY (owner_user_id) REFERENCES app_users (id),
    CONSTRAINT ck_media_files_byte_size_positive
        CHECK (byte_size > 0),
    CONSTRAINT ck_media_files_status
        CHECK (status IN ('PENDING', 'UPLOADED', 'FAILED')),
    CONSTRAINT ck_media_files_content_type
        CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp'))
);

CREATE INDEX IF NOT EXISTS idx_media_files_owner_status
    ON media_files (owner_user_id, status);

CREATE INDEX IF NOT EXISTS idx_media_files_status_created
    ON media_files (status, created_at);

ALTER TABLE postcards
    ADD COLUMN IF NOT EXISTS media_file_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'uk_postcards_media_file'
    ) THEN
        ALTER TABLE postcards
            ADD CONSTRAINT uk_postcards_media_file UNIQUE (media_file_id);
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_postcards_media_file'
    ) THEN
        ALTER TABLE postcards
            ADD CONSTRAINT fk_postcards_media_file
            FOREIGN KEY (media_file_id) REFERENCES media_files (id);
    END IF;
END $$;
